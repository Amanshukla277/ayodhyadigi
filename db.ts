export async function all(table: string): Promise<Row[]> {
  await initializeDatabase();

  if (!['services', 'projects', 'enquiries'].includes(table)) {
    throw new Error('Invalid table');
  }

  const orderBy =
    table === 'enquiries'
      ? 'id DESC'
      : 'sort_order ASC, id DESC';

  const result = await pool.query(
    `SELECT * FROM ${table} ORDER BY ${orderBy}`
  );

  return result.rows;
}

export async function settings(): Promise<Row> {
  await initializeDatabase();

  const result = await pool.query(
    'SELECT * FROM site_settings WHERE id = 1'
  );

  return result.rows[0];
}

const schemas: Record<string, string[]> = {
  services: [
    'title',
    'slug',
    'description',
    'icon',
    'published',
    'sort_order',
  ],
  projects: [
    'title',
    'category',
    'description',
    'image_url',
    'project_url',
    'published',
    'featured',
    'sort_order',
  ],
};

function getValues(cols: string[], data: Row) {
  return cols.map((key) =>
    data[key] ??
    (key === 'published'
      ? 1
      : key === 'featured' || key === 'sort_order'
        ? 0
        : '')
  );
}

export async function insert(table: string, data: Row) {
  await initializeDatabase();

  const cols = schemas[table];

  if (!cols) {
    throw new Error('Invalid table');
  }

  const values = getValues(cols, data);
  const placeholders = cols.map((_, i) => `$${i + 1}`).join(', ');

  const result = await pool.query(
    `INSERT INTO ${table} (${cols.join(', ')})
     VALUES (${placeholders})
     RETURNING id`,
    values
  );

  return result.rows[0].id;
}

export async function update(table: string, id: number, data: Row) {
  await initializeDatabase();

  const cols = schemas[table];

  if (!cols) {
    throw new Error('Invalid table');
  }

  const values = getValues(cols, data);
  const assignments = cols
    .map((key, i) => `${key} = $${i + 1}`)
    .join(', ');

  await pool.query(
    `UPDATE ${table} SET ${assignments}
     WHERE id = $${cols.length + 1}`,
    [...values, id]
  );
}

export async function remove(table: string, id: number) {
  await initializeDatabase();

  if (!['services', 'projects', 'enquiries'].includes(table)) {
    throw new Error('Invalid table');
  }

  await pool.query(
    `DELETE FROM ${table} WHERE id = $1`,
    [id]
  );
}

export async function saveSettings(data: Row) {
  await initializeDatabase();

  const cols = [
    'brand_name',
    'tagline',
    'logo_url',
    'email',
    'phone',
    'whatsapp',
    'address',
    'hero_title',
    'hero_description',
    'about_title',
    'about_text',
    'seo_title',
    'seo_description',
    'seo_keywords',
    'primary_color',
    'accent_color',
  ];

  const assignments = cols
    .map((key, i) => `${key} = $${i + 1}`)
    .join(', ');

  await pool.query(
    `UPDATE site_settings SET ${assignments} WHERE id = 1`,
    cols.map((key) => String(data[key] ?? ''))
  );
}

export async function addEnquiry(data: Row) {
  await initializeDatabase();

  const result = await pool.query(
    `INSERT INTO enquiries
      (name, email, phone, service, message)
     VALUES ($1, $2, $3, $4, $5)
     RETURNING id`,
    [
      data.name,
      data.email,
      data.phone || '',
      data.service || '',
      data.message,
    ]
  );

  return result.rows[0].id;
}

export async function updateEnquiry(id: number, status: string) {
  await initializeDatabase();

  if (!['new', 'contacted', 'qualified', 'closed', 'spam'].includes(status)) {
    throw new Error('Invalid status');
  }

  await pool.query(
    'UPDATE enquiries SET status = $1 WHERE id = $2',
    [status, id]
  );
}

export async function count(table: string): Promise<number> {
  await initializeDatabase();

  if (!['services', 'projects', 'enquiries'].includes(table)) {
    return 0;
  }

  const result = await pool.query(
    `SELECT COUNT(*) AS n FROM ${table}`
  );

  return Number(result.rows[0].n);
}